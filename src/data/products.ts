function makeProduct(
  index: number,
  name: string,
  category: MainCategory,
  subcategory: string,
  gender: GenderFilter,
  ageGroup: AgeGroup,
  originalPrice: number,
  discountPercent: number,
  archetype: VisualArchetype,
  primaryColor: string,
  secondaryColor: string,
  accentColor: string,
  bgTone: string,
  motifLabel: string,
  pattern: Product['visual']['pattern'],
  sizes: string[],
  description: string,
  highlights: string[],
  badge?: Product['badge'],
  offerTag?: string
): Product {
  const id = `kidx-${String(index).padStart(3, '0')}`;
  const sku = `KX-IN-${String(index).padStart(4, '0')}`;
  const offerPrice = Math.round((originalPrice * (100 - discountPercent)) / 100);
  const rating = Number((4.4 + ((index * 7) % 6) * 0.1).toFixed(1));
  const reviewsCount = 24 + ((index * 19) % 240);

  return {
    id,
    sku,
    name,
    category,
    subcategory,
    gender,
    ageGroup,
    originalPrice,
    discountPercent,
    offerPrice,
    rating,
    reviewsCount,
    sizes,
    badge,
    offerTag,
    description,
    highlights,
    visual: {
      archetype,
      bgTone,
      primaryColor,
      secondaryColor,
      accentColor,
      motifLabel,
      pattern,
    },
  };
}

